# ============================================
# COSMOLOGICAL FUNCTIONS
# ============================================

def H(z):
    """Hubble parameter as function of redshift (HSE-modified)"""
    H0_SI = H0 / 3.086e19  # Convert to 1/s

    # HSE evolution function
    g_HSE = (1+z)**(-3) * (1 + phi_cosmo(z) * delta * np.sqrt(1+z))

    return H0_SI * np.sqrt(Omega_m*(1+z)**3 + Omega_Lambda + Omega_HSE*g_HSE)

def phi_cosmo(z):
    """Cosmological porosity factor"""
    return phi_BH * np.sqrt(1 + delta * z)

def comoving_distance(z):
    """Comoving distance in Mpc"""
    def integrand(zp):
        return c / (H(zp) * 3.086e19)  # Convert back to Mpc

    if z == 0:
        return 0

    result, _ = quad(integrand, 0, z)
    return result

def angular_diameter_distance(z):
    """Angular diameter distance"""
    return comoving_distance(z) / (1 + z)

# ============================================
# HSE LENSING KERNEL
# ============================================

def G_HSE(rho_bar, z):
    """
    HSE entropic cohesion term

    rho_bar: baryonic density at position (in M_sun/Mpc^3)
    z: redshift
    """
    # Critical density
    G_newton = 4.302e-6  # in (km/s)^2 Mpc/M_sun
    rho_crit = 3 * H(z)**2 / (8 * np.pi * G_newton)

    # Vacuum energy density (Eq 2.4)
    rho_vac = rho_crit * (1 - S_ratio) * delta

    # Entropic cohesion (Eq 3.28 simplified for cosmology)
    # G_HSE ∝ rho_bar * phi_cosmo * delta
    return rho_bar * phi_cosmo(z) * delta * (rho_vac / rho_crit)

def lensing_kernel(z_source, z_lens):
    """
    Lensing efficiency function
    """
    if z_lens >= z_source:
        return 0

    D_lens = angular_diameter_distance(z_lens)
    D_source = angular_diameter_distance(z_source)
    D_lens_source = angular_diameter_distance(z_source - z_lens)

    return D_lens * D_lens_source / D_source / (1 + z_lens)

def kappa_HSE(theta, z_source, rho_bar_profile, z_array):
    """
    HSE convergence (lensing signal) at angular position theta

    theta: angular position (in arcmin)
    z_source: source redshift
    rho_bar_profile: function rho_bar(z) giving baryonic density
    z_array: redshift grid for integration
    """
    # Convert angular position to physical distance (simplified)
    # Assuming small angles

    kappa = 0
    dz = z_array[1] - z_array[0]

    for z_lens in z_array:
        if z_lens >= z_source:
            break

        # Baryonic density at this redshift
        rho_bar = rho_bar_profile(z_lens)

        # HSE cohesion contribution
        G = G_HSE(rho_bar, z_lens)

        # Lensing kernel
        W = lensing_kernel(z_source, z_lens)

        # Accumulate convergence
        # Factor includes geometric and normalization terms
        prefactor = 3 * Omega_HSE * H(0)**2 / (2 * c**2)
        kappa += prefactor * W * G * dz

    return kappa

