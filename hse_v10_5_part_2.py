# -----------------------------
# 2. HSE v10.1 Physik-Funktionen
# -----------------------------

def rotation_velocity_classic(r, M):
    """Klassische Newton/Kepler Geschwindigkeit."""
    return np.sqrt(G * M / r)

def rotation_velocity_hse(r, M, phi_BH=phi_BH, delta=delta):
    """
    HSE v10.1: Kombiniert Newton-Gravitation mit entropischer
    Zusatzbeschleunigung durch Raum-Porosität.
    """
    # 1. Klassische Beschleunigung g_N
    v_n = rotation_velocity_classic(r, M)
    g_N = v_n**2 / r

    # 2. Die HSE-Beschleunigungsschwelle (a_0)
    # Herleitung: In HSE skaliert der Zusammenhalt mit der Porosität
    # relativ zur Hubble-Expansion.
    H0 = 2.26e-18 # s^-1 (ca. 70 km/s/Mpc)
    # a_0 = c * H0 * Korrekturfaktor(phi, delta)
    a_0_hse = c * H0 * (phi_BH * (1 + delta)) * 0.82

    # 3. Entropische Kraft-Kopplung (Deep MOND-HSE Hybrid)
    # Wir nutzen die Interpolation: g_eff = sqrt(g_N^2 + g_N * a_0)
    # Dies sorgt dafür, dass bei kleinen Radien Newton dominiert und
    # bei großen Radien die Kurve flach wird.
    g_eff = g_N * (0.5 + 0.5 * np.sqrt(1 + 4 * a_0_hse / g_N))

    return np.sqrt(g_eff * r)

# -----------------------------
# 3. MCMC für Parameter-Validierung
# -----------------------------
print("Starte MCMC Sampling für HSE v10.1 (Galactic Scale)...")

def log_likelihood(params, r, v_target):
    phi, d = params
    v_model = rotation_velocity_hse(r, M_gal, phi, d)
    # Fokus auf die Flachheit am Rand (r > 15 kpc)
    return -0.5 * np.sum(((v_model[50:] - v_target[50:])**2 / (5e3)**2))

def log_prior(params):
    phi, d = params
    if 0.5 < phi < 0.75 and 0.04 < d < 0.09:
        return 0.0
    return -np.inf

def log_posterior(params, r, v_target):
    lp = log_prior(params)
    if not np.isfinite(lp): return -np.inf
    return lp + log_likelihood(params, r, v_target)

# MCMC Setup
ndim, nwalkers, nsteps = 2, 32, 1500
p0 = np.array([phi_BH, delta]) + 1e-3 * np.random.randn(nwalkers, ndim)
